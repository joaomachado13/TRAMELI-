-- Human-readable, immutable order references. Existing order UUIDs and relationships remain unchanged.
begin;

alter table public.trameli_orders
  add column public_code text;

create table public.trameli_order_code_counters (
  order_date date primary key,
  last_number integer not null check (last_number > 0)
);
alter table public.trameli_order_code_counters enable row level security;
revoke all on table public.trameli_order_code_counters from public, anon, authenticated;

with ranked as (
  select id,
    (created_at at time zone 'America/Sao_Paulo')::date as order_date,
    row_number() over (
      partition by (created_at at time zone 'America/Sao_Paulo')::date
      order by created_at, id
    ) as sequence_number
  from public.trameli_orders
)
update public.trameli_orders as orders
set public_code = 'TR-' || to_char(ranked.order_date, 'DDMMYY') || '-' ||
  lpad(ranked.sequence_number::text, greatest(3, length(ranked.sequence_number::text)), '0')
from ranked
where orders.id = ranked.id;

alter table public.trameli_orders
  alter column public_code set not null,
  add constraint trameli_orders_public_code_format
    check (public_code ~ '^TR-[0-9]{6}-[0-9]{3,}$');

create unique index trameli_orders_public_code_uidx
  on public.trameli_orders(public_code);

insert into public.trameli_order_code_counters(order_date, last_number)
select (created_at at time zone 'America/Sao_Paulo')::date,
  max(substring(public_code from 11)::integer)
from public.trameli_orders
group by (created_at at time zone 'America/Sao_Paulo')::date
on conflict (order_date) do update
set last_number = greatest(
  public.trameli_order_code_counters.last_number,
  excluded.last_number
);

comment on column public.trameli_orders.public_code is
  'Human-readable immutable order reference, generated by the database; UUID id remains the internal key.';

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create function private.trameli_assign_order_public_code()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_day date;
  v_next integer;
begin
  if tg_op = 'UPDATE' then
    if new.public_code is distinct from old.public_code then
      raise exception 'Order code is immutable';
    end if;
    return new;
  end if;

  if new.public_code is not null and btrim(new.public_code) <> '' then
    raise exception 'Order code is assigned by the system';
  end if;

  v_day := (coalesce(new.created_at, now()) at time zone 'America/Sao_Paulo')::date;
  insert into public.trameli_order_code_counters(order_date, last_number)
  values (v_day, 1)
  on conflict (order_date) do update
    set last_number = public.trameli_order_code_counters.last_number + 1
  returning last_number into v_next;

  new.public_code := 'TR-' || to_char(v_day, 'DDMMYY') || '-' ||
    lpad(v_next::text, greatest(3, length(v_next::text)), '0');
  return new;
end;
$$;

revoke all on function private.trameli_assign_order_public_code() from public, anon, authenticated;

create trigger trameli_orders_public_code
before insert or update on public.trameli_orders
for each row execute function private.trameli_assign_order_public_code();

notify pgrst, 'reload schema';
commit;
